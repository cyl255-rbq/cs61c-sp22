# 初始化调试寄存器（注意框架只检查 ra, sp, t0, t1, t2, s0, s1, a0）
addi t0, x0, 10      # t0 = 10
addi t1, x0, 5       # t1 = 5

# 测试 ADD
add t2, t0, t1       # t2 = 10 + 5 = 15
# 测试 SUB (如果 sub 连线错了，t2 会变成 15)
sub s0, t2, t1       # s0 = 15 - 5 = 10
# 测试异或 XOR (常用于检查位运算逻辑)
xor s1, t0, t1       # s1 = 1010 ^ 0101 = 1111 (15)
# 测试逻辑左移 SLL
sll a0, t0, x0       # a0 = 10 << 0 = 10 (检查移位量为0是否正常)
addi a0, a0, 2       # a0 = 12
sll a0, a0, t1       # a0 = 12 << 5 = 384 (检查移位器 BSel 是否正确)